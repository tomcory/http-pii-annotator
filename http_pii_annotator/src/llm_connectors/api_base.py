from abc import ABC, abstractmethod
from collections.abc import Callable
from dataclasses import dataclass
from typing import Literal

ResponseFormat = Literal['text', 'json', 'json_schema']


@dataclass(frozen=True)
class Prompt:
    """
    A prompt, independent of the API it is sent to.

    Attributes:
        task: Name of the task the prompt belongs to
        system: System prompt
        messages: Conversation of user and assistant messages as dicts with 'role' and 'content'
        response_schema: JSON schema of the expected response
    """
    task: str
    system: str
    messages: tuple[dict, ...]
    response_schema: dict | None = None

    def with_system_message(self) -> list[dict]:
        """The conversation, preceded by the system prompt as a message with the role 'system'."""
        return [{"role": "system", "content": self.system}, *self.messages]


@dataclass(frozen=True)
class GenerationParams:
    """Sampling parameters of a completion."""
    temperature: float = 1.0
    max_tokens: int = 2048
    top_p: float | None = 1  # None: not sent, so that the API's own default applies
    seed: int | None = None


@dataclass(frozen=True)
class LLMResponse:
    """
    The text generated by a model and the number of tokens of the prompt and of the generated text.

    Attributes:
        finish_reason: Why the model stopped, as the API names it ('length' when the token limit cut the
            output off); None if the connector does not report it
        thinking_chars: Length of the reasoning that a thinking-capable model produced before its answer.
            The reasoning is not part of the text, but its tokens count towards the token limit.
    """
    text: str
    input_tokens: int = 0
    output_tokens: int = 0
    finish_reason: str | None = None
    thinking_chars: int = 0


class LLMClient(ABC):
    """
    Abstract base class for LLM API connectors.

    A connector only transports a prompt to its API and returns the response. It keeps no state between
    calls, so that it can be called from several threads.
    """

    #: Name of the API
    api: str

    def __init__(self, hostname: str = None, timeout: float = None):
        """
        Args:
            hostname: Base URL of the API endpoint (None for the API's default endpoint)
            timeout: Seconds after which a request to the API is aborted (None to wait indefinitely)
        """
        self.hostname = hostname
        self.timeout = timeout

    @abstractmethod
    def complete(
            self,
            model: str,
            prompt: Prompt,
            response_format: ResponseFormat = 'text',
            params: GenerationParams = GenerationParams(),
            model_options: dict = None,
            on_text: Callable[[str], None] = None
    ) -> LLMResponse:
        """
        Send a prompt to the model and return its response.

        Args:
            model: Name of the model as expected by the API
            prompt: The prompt
            response_format: Format of the response; 'json_schema' requests the prompt's response schema
            params: Sampling parameters
            model_options: Options of the request that only some APIs know. Each connector documents the ones
                it reads and ignores the others.
            on_text: Called with each piece of generated text, for APIs that stream their responses
        """
        pass

    def prepare(self, model: str):
        """Make the model available. Only required for APIs that manage locally hosted models."""
        pass

    def release(self, model: str):
        """Release the resources of the model. Only required for APIs that manage locally hosted models."""
        pass

    def close(self):
        """Close the connection to the API."""
        pass
