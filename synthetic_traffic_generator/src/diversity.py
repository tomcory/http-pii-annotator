"""
Diversity across generated messages.

When every message is generated by its own LLM call, the model no longer sees the other
messages of the scenario and tends to repeat itself (same paths, same names, same payloads).
The tracker gives the generator a memory of what already exists for a scenario, rejects
near-duplicates, and the report quantifies the diversity of a set of messages.
"""

import json
import re
import statistics
from collections import Counter
from difflib import SequenceMatcher

# bodies shorter than this are not checked for near-duplicates (e.g. '{"success":true}')
MIN_DUPLICATE_BODY_CHARS = 200
DUPLICATE_SIMILARITY = 0.9
ID_PATTERN = re.compile(r"\d")


def _http(message: dict) -> dict:
    return message.get("http_request") or message.get("http_response") or {}


def _path(message: dict) -> str:
    path = _http(message).get("path")
    return path if isinstance(path, str) else ""


def _body(message: dict) -> str:
    body = _http(message).get("body")
    return body if isinstance(body, str) else ""


def _is_unique_value(value: str) -> bool:
    """Whether a PII value identifies one user or device (email addresses, long identifiers and tokens)."""
    if "@" in value and "." in value:
        return True
    return len(value) >= 16 and len(ID_PATTERN.findall(value)) >= 4 and " " not in value


def body_keys(body: str) -> frozenset:
    """The set of keys of a JSON or form-encoded body (empty for other formats)."""
    try:
        parsed = json.loads(body)
    except (ValueError, TypeError):
        parsed = None

    keys = set()
    if isinstance(parsed, (dict, list)):
        def walk(value):
            if isinstance(value, dict):
                for key, child in value.items():
                    keys.add(key)
                    walk(child)
            elif isinstance(value, list):
                for child in value:
                    walk(child)
        walk(parsed)
    elif "=" in body and " " not in body.strip():
        keys.update(pair.split("=", 1)[0] for pair in body.strip().split("&") if "=" in pair)
    return frozenset(keys)


class DiversityTracker:
    """Remembers the messages generated per scenario and detects repetitions."""

    def __init__(self):
        self._messages: dict[str, list[dict]] = {}
        # identifying values of all scenarios: value -> id of the message that introduced it
        self._identifiers: dict[str, str] = {}

    def add(self, scenario_id: str, message: dict):
        self._messages.setdefault(scenario_id, []).append(message)
        for annotation in message.get("pii_annotations", []):
            value = annotation.get("value")
            if isinstance(value, str) and _is_unique_value(value):
                self._identifiers.setdefault(value, message.get("id"))

    def digest(self, scenario_id: str, max_paths: int = 12, max_values: int = 30) -> dict:
        """What already exists for a scenario, to be shown to the LLM as things not to repeat."""
        messages = self._messages.get(scenario_id, [])
        if not messages:
            return {}

        paths = []
        for message in messages:
            path = _path(message).split("?", 1)[0]
            if path and path not in paths:
                paths.append(path)

        values = []
        for message in reversed(messages):
            for annotation in message.get("pii_annotations", []):
                value = annotation.get("value")
                if isinstance(value, str) and 3 <= len(value) <= 60 and value not in values:
                    values.append(value)

        top_keys = Counter()
        for message in messages:
            body = _body(message)
            try:
                parsed = json.loads(body)
            except (ValueError, TypeError):
                continue
            if isinstance(parsed, dict):
                top_keys[", ".join(list(parsed)[:8])] += 1

        digest = {"messages_so_far": len(messages)}
        if paths:
            digest["paths_already_used"] = paths[-max_paths:]
        if values:
            digest["pii_values_already_used"] = values[:max_values]
        if top_keys:
            digest["body_layouts_already_used"] = [layout for layout, _ in top_keys.most_common(5)]
        return digest

    def check(self, scenario_id: str, message: dict, prefix: str, own_values=()) -> list[str]:
        """
        Errors if the message repeats an earlier message of the scenario.

        own_values: values the message may share with another message (a response repeats
        the values of its own request).
        """
        errors = []
        earlier = self._messages.get(scenario_id, [])

        body = _body(message)
        path = _path(message)

        if len(body) >= MIN_DUPLICATE_BODY_CHARS:
            for other in earlier:
                other_body = _body(other)
                if not 0.8 <= len(other_body) / len(body) <= 1.25:
                    continue
                matcher = SequenceMatcher(None, body, other_body, autojunk=False)
                if matcher.quick_ratio() >= DUPLICATE_SIMILARITY and matcher.ratio() >= DUPLICATE_SIMILARITY:
                    errors.append(
                        f"{prefix}: Body is nearly identical to that of {other.get('id')}; "
                        f"use a different structure and different values"
                    )
                    break
        elif path and "http_request" in message and not body:
            if any(_path(other) == path and not _body(other) for other in earlier):
                errors.append(f"{prefix}: Path and query are identical to an earlier request; vary them")

        # identifying values must be unique across the whole dataset, not only within the scenario
        reused = [
            annotation["value"] for annotation in message.get("pii_annotations", [])
            if isinstance(annotation.get("value"), str) and annotation["value"] in self._identifiers
            and annotation["value"] not in own_values
        ]
        if reused:
            shown = ", ".join(f"'{value}'" for value in reused[:4])
            errors.append(f"{prefix}: Identifying values were already used in another message ({shown}); invent new ones")

        return errors


def diversity_report(messages: list[dict]) -> dict:
    """Diversity statistics of a set of messages (negative controls excluded)."""
    messages = [m for m in messages if not m.get("negative_control", False)]
    if not messages:
        return {"messages": 0}

    by_scenario: dict[str, list[dict]] = {}
    for message in messages:
        by_scenario.setdefault(message.get("scenario_id") or message.get("scenario") or "", []).append(message)

    paths = [_path(m).split("?", 1)[0] for m in messages if _path(m)]
    hosts = [
        header.get("value") for m in messages for header in (_http(m).get("headers") or [])
        if isinstance(header, dict) and str(header.get("key", "")).lower() == "host"
    ]
    values = [
        a["value"] for m in messages for a in m.get("pii_annotations", []) if isinstance(a.get("value"), str)
    ]
    unique_values = [v for v in values if _is_unique_value(v)]
    value_counts = Counter(values)

    # structural similarity of bodies within a scenario: Jaccard similarity of their key sets
    similarities, duplicates = [], 0
    for scenario_messages in by_scenario.values():
        keyed = [(m, body_keys(_body(m))) for m in scenario_messages]
        keyed = [(m, keys) for m, keys in keyed if keys]
        for i in range(len(keyed)):
            for j in range(i + 1, len(keyed)):
                a, b = keyed[i][1], keyed[j][1]
                similarities.append(len(a & b) / len(a | b))
        bodies = [_body(m) for m in scenario_messages if len(_body(m)) >= MIN_DUPLICATE_BODY_CHARS]
        duplicates += len(bodies) - len(set(bodies))

    statuses = Counter(str(_http(m).get("status_code")) for m in messages if "http_response" in m)
    methods = Counter(str(_http(m).get("method")) for m in messages if "http_request" in m)
    content_types = Counter()
    for message in messages:
        content_type = next(
            (str(h.get("value", "")).split(";")[0].strip().lower() for h in (_http(message).get("headers") or [])
             if isinstance(h, dict) and str(h.get("key", "")).lower() == "content-type"), "(none)"
        )
        content_types[content_type] += 1

    report = {
        "messages": len(messages),
        "unique_path_share": round(len(set(paths)) / len(paths), 3) if paths else None,
        "unique_hosts": len(set(hosts)) if hosts else None,
        "unique_pii_value_share": round(len(value_counts) / len(values), 3) if values else None,
        "unique_identifier_share": round(len(set(unique_values)) / len(unique_values), 3) if unique_values else None,
        "most_repeated_pii_values": [[v, c] for v, c in value_counts.most_common(5) if c > 1],
        "body_key_similarity_mean": round(statistics.mean(similarities), 3) if similarities else None,
        "exact_duplicate_bodies": duplicates,
        "content_types": dict(content_types.most_common(8)),
    }
    if methods:
        report["methods"] = dict(methods)
    if statuses:
        report["status_codes"] = dict(statuses.most_common(8))
    return report
